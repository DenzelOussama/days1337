#include <unistd.h>

void	ft_putnbr(int nb)
{
	char	mod;

	if (nb == -2147483648)
	{
		write(1, "-2147483648", 11);
		return ;
	}
	if (nb < 0)
	{
		write(1, "-", 1);
		nb = -nb;
	}
	if (nb == 0)
	{
		write(1, "0", 1);
		return ;
	}
	if (nb >= 10)
	{
		ft_putnbr(nb / 10);
	}
	mod = nb % 10 + '0';
	write(1, &mod, 1);
}
